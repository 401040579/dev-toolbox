export function getToolCopy(tool: Pick<ToolDefinition, 'id'>, t: TFunction) {
  const key = TOOL_I18N_KEYS[tool.id];
  return { name: t(`tools.${key}.title`), description: t(`tools.${key}.description`) };
}

export function getTransformCopy(transform: Pick<TransformDefinition, 'id'>, t: TFunction) {
  return {
    name: t(`transforms.${transform.id}.name`),
    description: t(`transforms.${transform.id}.description`),
  };
}
